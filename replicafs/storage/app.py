"""Storage node.

A storage node is deliberately dumb: it stores opaque chunks on its local disk
and tells the metadata server it is alive. It knows nothing about files, only
chunk ids. All the intelligence (which node has what, replication, versioning)
lives in the metadata server, exactly like chunkservers in GFS / DataNodes in HDFS.
"""
import logging
import os
import shutil
import threading
import time
from contextlib import asynccontextmanager
from pathlib import Path

import httpx
from fastapi import FastAPI, HTTPException, Request, Response
from pydantic import BaseModel

from replicafs.common import sha256_hex

NODE_ID = os.environ.get("NODE_ID", "node1")
# The address OTHER services use to reach this node (inside docker it is http://node1:8001).
NODE_URL = os.environ.get("NODE_URL", "http://localhost:8001")
METADATA_URL = os.environ.get("METADATA_URL", "http://localhost:8000")
DATA_DIR = Path(os.environ.get("DATA_DIR", f"./data/{NODE_ID}"))
HEARTBEAT_INTERVAL = float(os.environ.get("HEARTBEAT_INTERVAL", "3"))

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
log = logging.getLogger(f"storage.{NODE_ID}")


def chunk_path(chunk_id: str) -> Path:
    # Chunk ids are hex uuids generated by the metadata server; reject anything
    # that could escape DATA_DIR.
    if not chunk_id.isalnum():
        raise HTTPException(status_code=400, detail="invalid chunk id")
    return DATA_DIR / chunk_id


def write_chunk_atomically(path: Path, data: bytes) -> None:
    # Write to a temp file and rename. If the process dies mid-write we never
    # leave a half-written chunk that looks valid to a later reader.
    tmp = path.with_suffix(".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)


def local_chunk_count() -> int:
    return sum(1 for p in DATA_DIR.iterdir() if p.suffix != ".tmp")


def heartbeat_loop() -> None:
    """Tell the metadata server we're alive every HEARTBEAT_INTERVAL seconds.

    If this node crashes, the heartbeats stop, and the metadata server marks us
    DEAD after a timeout. That silence IS the failure detector.
    """
    while True:
        try:
            httpx.post(
                f"{METADATA_URL}/nodes/heartbeat",
                json={
                    "node_id": NODE_ID,
                    "url": NODE_URL,
                    "chunk_count": local_chunk_count(),
                    "free_bytes": shutil.disk_usage(DATA_DIR).free,
                },
                timeout=2,
            )
        except Exception as e:  # metadata server may be down; keep trying
            log.warning("heartbeat failed: %s", e)
        time.sleep(HEARTBEAT_INTERVAL)


@asynccontextmanager
async def lifespan(app: FastAPI):
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    threading.Thread(target=heartbeat_loop, daemon=True).start()
    log.info("storage node %s serving %s, reporting to %s", NODE_ID, DATA_DIR, METADATA_URL)
    yield


app = FastAPI(title=f"ReplicaFS storage node {NODE_ID}", lifespan=lifespan)


@app.get("/health")
def health():
    return {"node_id": NODE_ID, "chunks": local_chunk_count()}


@app.put("/chunks/{chunk_id}")
async def put_chunk(chunk_id: str, request: Request):
    data = await request.body()
    actual = sha256_hex(data)
    expected = request.headers.get("x-checksum")
    if expected and expected != actual:
        raise HTTPException(status_code=422, detail="checksum mismatch: chunk corrupted in transit")
    write_chunk_atomically(chunk_path(chunk_id), data)
    return {"chunk_id": chunk_id, "checksum": actual, "size": len(data)}


@app.get("/chunks/{chunk_id}")
def get_chunk(chunk_id: str):
    path = chunk_path(chunk_id)
    if not path.exists():
        raise HTTPException(status_code=404, detail="chunk not on this node")
    data = path.read_bytes()
    # The checksum we report is computed from what's on disk *now*, so the
    # metadata server can detect bit-rot by comparing it to the one it recorded at upload.
    return Response(content=data, media_type="application/octet-stream", headers={"X-Checksum": sha256_hex(data)})


@app.delete("/chunks/{chunk_id}")
def delete_chunk(chunk_id: str):
    chunk_path(chunk_id).unlink(missing_ok=True)
    return {"deleted": chunk_id}


class ReplicateRequest(BaseModel):
    chunk_id: str
    source_url: str
    checksum: str


@app.post("/replicate")
def replicate(req: ReplicateRequest):
    """Pull a chunk from another node. Called by the metadata server's re-replicator
    when a chunk has fewer live copies than the replication factor."""
    try:
        r = httpx.get(f"{req.source_url}/chunks/{req.chunk_id}", timeout=30)
        r.raise_for_status()
    except httpx.HTTPError as e:
        raise HTTPException(status_code=502, detail=f"could not fetch from source: {e}")
    if sha256_hex(r.content) != req.checksum:
        raise HTTPException(status_code=422, detail="source replica is corrupt")
    write_chunk_atomically(chunk_path(req.chunk_id), r.content)
    log.info("replicated chunk %s from %s", req.chunk_id, req.source_url)
    return {"chunk_id": req.chunk_id, "replicated_from": req.source_url}
